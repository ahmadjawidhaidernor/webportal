-- Store one or more recorded videos per lesson.
create table if not exists public.lesson_videos (
  id bigint generated always as identity primary key,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  title text not null,
  video_url text not null,
  created_at timestamptz not null default now()
);

alter table public.lesson_videos enable row level security;

drop policy if exists "Authenticated users can read lesson_videos" on public.lesson_videos;
create policy "Authenticated users can read lesson_videos"
on public.lesson_videos for select
to authenticated
using (true);

drop policy if exists "Admin can manage lesson_videos" on public.lesson_videos;
create policy "Admin can manage lesson_videos"
on public.lesson_videos for all
to authenticated
using ((auth.jwt() ->> 'email') = 'admin@gmail.com')
with check ((auth.jwt() ->> 'email') = 'admin@gmail.com');

alter table public.lessons drop column if exists video_url;

-- Create the activity_log table
create table if not exists public.activity_log (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  lesson_id bigint references public.lessons(id) on delete set null,
  action_type text not null check (action_type in ('login', 'view', 'download', 'video_view')),
  created_at timestamptz not null default now()
);

-- Allow the student portal to record video views on existing installations.
alter table public.activity_log
drop constraint if exists activity_log_action_type_check;

alter table public.activity_log
add constraint activity_log_action_type_check
check (action_type in ('login', 'view', 'download', 'video_view'));

alter table public.activity_log enable row level security;

-- Students can insert only their own rows
create policy "Students can insert their own activity"
on public.activity_log
for insert
to authenticated
with check (
  student_id = auth.uid()
);

drop policy if exists "Students can read their own activity" on public.activity_log;
create policy "Students can read their own activity"
on public.activity_log
for select
to authenticated
using (
  student_id = auth.uid()
);

-- Only the admin can read activity rows
create policy "Admin can read all activity"
on public.activity_log
for select
to authenticated
using (
  exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and lower(p.email) = 'admin@gmail.com'
  )
);

